export interface ChessPieceProps {
  t: ChessPieceType;
  c: ChessPieceColor;
  className?: string;
  /** Non-decorative use: gives the svg role="img" + aria-label. */
  label?: string;
}

export function ChessPiece({ t, c, className, label }: ChessPieceProps) {
  const s = SHAPES[t];
  const cls = [styles.root, className].filter(Boolean).join(' ');
  return (
    <svg
      viewBox="0 0 45 45"
      className={cls}
      data-c={c}
      aria-hidden={label ? undefined : true}
      role={label ? 'img' : undefined}
      aria-label={label}
      focusable="false"
    >
      <g data-part="sil">
        {s.sil.map((d) => (
          <path key={d} d={d} />
        ))}
      </g>
      {s.det.length > 0 && (
        <g data-part="det">
          {s.det.map((d) => (
            <path key={d} d={d} />
          ))}
        </g>
      )}
    </svg>
  );
}
